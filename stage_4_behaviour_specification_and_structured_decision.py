ALLOWED_ACTIONS = {
    "answer",
    "tool",
    "ask_user",
    "escalate"
}


ALLOWED_TOOLS = {
    "newsdata",
    "gnews",
    "google_news_rss"
}


BEHAVIOUR_SPEC = {
    "ROLE": "News curation assistant",

    "GOAL": (
        "Collect and organize relevant public news "
        "for the user."
    ),

    "AVAILABLE_INFORMATION": [
        "User query",
        "News gathered from approved public sources"
    ],

    "AVAILABLE_TOOLS": [
        "NewsData.io",
        "GNews",
        "Google News RSS"
    ],

    "RULES": [
        "Use public information only.",
        "Identify the news source.",
        "Do not perform purchases.",
        "Do not perform financial actions.",
        "Do not perform irreversible actions."
    ],

    "OUTPUT_CONTRACT": [
        "Return a structured decision.",
        "Use only an allowed action.",
        "For a tool action, identify the tool.",
        "For a tool action, provide tool arguments.",
        "Provide a reason for the decision."
    ]
}


def validate_decision(decision):

    if not isinstance(decision, dict):
        return False, "Decision must be a dictionary."

    required_fields = [
        "action",
        "reason"
    ]

    for field in required_fields:

        if field not in decision:
            return False, "Missing field: " + field

    action = decision["action"]

    if action not in ALLOWED_ACTIONS:
        return False, "Action is not allowed."

    reason = decision["reason"]

    if not isinstance(reason, str):
        return False, "Reason must be text."

    if reason.strip() == "":
        return False, "Reason cannot be empty."

    if action == "tool":

        if "tool" not in decision:
            return False, "Tool is required."

        if "args" not in decision:
            return False, "Tool arguments are required."

        tool = decision["tool"]

        if tool not in ALLOWED_TOOLS:
            return False, "Requested tool is not approved."

        args = decision["args"]

        if not isinstance(args, dict):
            return False, "Tool arguments must be a dictionary."

        if "query" not in args:
            return False, "Tool query is required."

        query = args["query"]

        if not isinstance(query, str):
            return False, "Tool query must be text."

        if query.strip() == "":
            return False, "Tool query cannot be empty."

    return True, "Decision is valid."


def create_decision(user_query):

    if not isinstance(user_query, str):

        return {
            "action": "ask_user",
            "reason": "The user query must be text."
        }

    user_query = user_query.strip()

    if user_query == "":

        return {
            "action": "ask_user",
            "reason": "The user needs to provide a news topic."
        }

    return {
        "action": "tool",
        "tool": "newsdata",
        "args": {
            "query": user_query,
            "max_results": 5
        },
        "reason": (
            "Current news requires an approved "
            "public news source."
        )
    }


