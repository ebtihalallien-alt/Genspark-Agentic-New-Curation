"""
Genspark Agentic News Curation System
Stage 3: Model Boundary

Concept:
    Model Boundary

Purpose:
    Define a provider-neutral interface between the agent system
    and the language model.

The rest of the application should communicate with the model
through ModelClient.generate().
"""


class ModelClient:

    def generate(self, messages):
        raise NotImplementedError(
            "ModelClient.generate() must be implemented by a model provider."
        )


class MockModelClient(ModelClient):

    def generate(self, messages):

        if not isinstance(messages, list):
            raise ValueError("messages must be a list.")

        if len(messages) == 0:
            raise ValueError("messages cannot be empty.")

        last_message = messages[-1]

        if not isinstance(last_message, dict):
            raise ValueError("Each message must be a dictionary.")

        user_content = last_message.get("content", "")

        if not isinstance(user_content, str):
            raise ValueError("Message content must be text.")

        return (
            "Model received the user request: "
            + user_content
        )


if __name__ == "__main__":

    messages = [
        {
            "role": "user",
            "content": "Find recent news about Artificial Intelligence."
        }
    ]

    model = MockModelClient()

    response = model.generate(messages)

    print("Model Response:")
    print(response)