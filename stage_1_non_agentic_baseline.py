def baseline_answer(user_query):

    if not isinstance(user_query, str):
        return "Invalid user query."

    user_query = user_query.strip()

    if user_query == "":
        return "Please enter a news topic or question."

    return (
        "Baseline received the user query: "
        + user_query
        + "\n"
        + "This baseline does not use external news sources yet."
    )


