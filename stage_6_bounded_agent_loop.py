"""
Genspark Agentic News Curation System
Stage 6: Bounded Agent Loop

Flow:
OBSERVE -> DECIDE -> VALIDATE -> ACT -> OBSERVE RESULT

Purpose:
Connect the behaviour decision, tool validation,
and approved news tools inside a bounded agent loop.

Security:
API keys are not stored in this file.
They are provided at runtime through environment variables.
"""

import os
import importlib.util


MAX_TURNS = 3


def load_module(file_name, module_name):

    spec = importlib.util.spec_from_file_location(
        module_name,
        file_name
    )

    if spec is None or spec.loader is None:

        raise ImportError(
            "Could not load module: " + file_name
        )

    module = importlib.util.module_from_spec(spec)

    spec.loader.exec_module(module)

    return module


news_tools = load_module(
    "02_news_tools.py",
    "news_tools"
)

behavior = load_module(
    "04_behavior_and_decision.py",
    "behavior"
)

tool_validation = load_module(
    "05_tool_validation.py",
    "tool_validation"
)


def observe(user_query):

    return {
        "user_query": user_query,
        "last_result": None
    }


def decide(state):

    user_query = state["user_query"]

    if not isinstance(user_query, str):

        return {
            "action": "ask_user",
            "reason": "The user query must be text."
        }

    if user_query.strip() == "":

        return {
            "action": "ask_user",
            "reason": "A news topic is required."
        }

    return behavior.create_decision(user_query)


def validate(action):

    if action["action"] == "tool":

        return tool_validation.validate_tool_request(
            action
        )

    return behavior.validate_decision(action)


def act(action, state):

    if action["action"] == "ask_user":

        return {
            "status": "WAITING_FOR_USER",
            "message": action["reason"]
        }

    if action["action"] == "answer":

        return {
            "status": "COMPLETED",
            "message": "Answer is ready."
        }

    if action["action"] == "escalate":

        return {
            "status": "ESCALATED",
            "message": action["reason"]
        }

    tool_name = action["tool"]
    args = action["args"]

    if tool_name == "newsdata":

        api_key = os.getenv("NEWSDATA_API_KEY")

        if not api_key:

            return {
                "status": "FAILED_SAFELY",
                "message": "NewsData API key is not configured."
            }

        articles = news_tools.get_newsdata_news(
            args["query"],
            api_key,
            args.get("max_results", 5)
        )

    elif tool_name == "gnews":

        api_key = os.getenv("GNEWS_API_KEY")

        if not api_key:

            return {
                "status": "FAILED_SAFELY",
                "message": "GNews API key is not configured."
            }

        articles = news_tools.get_gnews_news(
            args["query"],
            api_key,
            args.get("max_results", 5)
        )

    elif tool_name == "google_news_rss":

        articles = news_tools.get_google_news_rss(
            args["query"],
            args.get("max_results", 5)
        )

    else:

        return {
            "status": "FAILED_SAFELY",
            "message": "Unknown tool."
        }

    return {
        "status": "TOOL_EXECUTED",
        "tool": tool_name,
        "article_count": len(articles),
        "articles": articles
    }


def run_agent(user_query):

    state = observe(user_query)

    print("Agent Run Started")
    print("-----------------")

    for turn in range(1, MAX_TURNS + 1):

        print()
        print("Turn:", turn)

        action = decide(state)

        print("Decision:")
        print(action)

        is_valid, validation_message = validate(action)

        print()
        print("Validation:")
        print(validation_message)

        if not is_valid:

            print()
            print("Terminal State: FAILED_SAFELY")
            return

        try:

            result = act(action, state)

        except Exception as error:

            result = {
                "status": "TOOL_ERROR",
                "message": str(error)
            }

        print()
        print("Action Result:")

        if result["status"] == "TOOL_EXECUTED":

            print({
                "status": result["status"],
                "tool": result["tool"],
                "article_count": result["article_count"]
            })

        else:

            print(result)

        state["last_result"] = result

        if result["status"] == "TOOL_EXECUTED":

            print()
            print("Terminal State: COMPLETED")
            return

        if result["status"] in {
            "WAITING_FOR_USER",
            "COMPLETED",
            "ESCALATED",
            "FAILED_SAFELY"
        }:

            print()
            print("Terminal State:", result["status"])
            return

        if result["status"] == "TOOL_ERROR":

            if turn < MAX_TURNS:

                print()
                print(
                    "Agent will retry within the turn budget."
                )

            else:

                print()
                print("Terminal State: FAILED_SAFELY")
                return

    print()
    print("Terminal State: BUDGET_EXHAUSTED")


if __name__ == "__main__":

    user_query = (
        "Find recent news about Artificial Intelligence."
    )

    run_agent(user_query)