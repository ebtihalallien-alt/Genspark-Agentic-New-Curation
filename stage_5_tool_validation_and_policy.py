ALLOWED_TOOLS = {
    "newsdata",
    "gnews",
    "google_news_rss"
}


TOOL_CATALOG = {
    "newsdata": {
        "purpose": "Collect recent public news articles.",
        "source": "NewsData.io",
        "permissions": "Read public news",
        "side_effect": "None",
        "timeout_seconds": 15,
        "expected_errors": "API or network error"
    },

    "gnews": {
        "purpose": "Collect recent public news articles.",
        "source": "GNews",
        "permissions": "Read public news",
        "side_effect": "None",
        "timeout_seconds": 15,
        "expected_errors": "API or network error"
    },

    "google_news_rss": {
        "purpose": "Collect recent public news through RSS.",
        "source": "Google News RSS",
        "permissions": "Read public news",
        "side_effect": "None",
        "timeout_seconds": 15,
        "expected_errors": "Network or RSS error"
    }
}


FORBIDDEN_TERMS = {
    "purchase",
    "buy",
    "payment",
    "transfer money",
    "financial transaction"
}


def validate_tool_request(decision):

    # Schema validation
    if not isinstance(decision, dict):
        return False, "Decision must be a dictionary."

    if decision.get("action") != "tool":
        return False, "Decision action must be 'tool'."

    if "tool" not in decision:
        return False, "Tool is required."

    if "args" not in decision:
        return False, "Tool arguments are required."

    # Reference validation
    tool_name = decision["tool"]

    if tool_name not in ALLOWED_TOOLS:
        return False, "Tool is not approved."

    if tool_name not in TOOL_CATALOG:
        return False, "Tool has no catalog entry."

    # Argument validation
    args = decision["args"]

    if not isinstance(args, dict):
        return False, "Tool arguments must be a dictionary."

    if "query" not in args:
        return False, "Tool query is required."

    query = args["query"]

    if not isinstance(query, str):
        return False, "Tool query must be text."

    query = query.strip()

    if query == "":
        return False, "Tool query cannot be empty."

    # max_results validation
    if "max_results" in args:

        max_results = args["max_results"]

        if not isinstance(max_results, int):
            return False, "max_results must be an integer."

        if max_results < 1 or max_results > 10:
            return False, "max_results must be between 1 and 10."

    # Policy validation
    query_lower = query.lower()

    for forbidden_term in FORBIDDEN_TERMS:

        if forbidden_term in query_lower:
            return False, "Request violates the project safety policy."

    # Permission validation
    permissions = TOOL_CATALOG[tool_name]["permissions"]

    if permissions != "Read public news":
        return False, "Tool permissions are not allowed."

    return True, "Tool request is approved."


