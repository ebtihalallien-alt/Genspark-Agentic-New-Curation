def require_text(value, field_name):

    if not isinstance(value, str) or value.strip() == "":
        raise ValueError(
            field_name + " must be a non-empty string."
        )


def validate_max_results(max_results):

    if not isinstance(max_results, int):
        raise ValueError(
            "max_results must be an integer."
        )

    if max_results < 1 or max_results > 10:
        raise ValueError(
            "max_results must be between 1 and 10."
        )


def get_newsdata_news(query, api_key, max_results=5):

    require_text(query, "query")
    require_text(api_key, "api_key")
    validate_max_results(max_results)

    url = "https://newsdata.io/api/1/latest"

    params = {
        "apikey": api_key,
        "q": query,
        "language": "en"
    }

    try:

        response = requests.get(
            url,
            params=params,
            timeout=15
        )

        response.raise_for_status()

        data = response.json()

    except requests.RequestException as error:

        raise RuntimeError(
            "NewsData request failed: " + str(error)
        )

    results = data.get("results", [])

    articles = []

    for item in results[:max_results]:

        articles.append({
            "source": "NewsData.io",
            "title": item.get("title"),
            "description": item.get("description"),
            "url": item.get("link"),
            "published_at": item.get("pubDate")
        })

    return articles


def get_gnews_news(query, api_key, max_results=5):

    require_text(query, "query")
    require_text(api_key, "api_key")
    validate_max_results(max_results)

    url = "https://gnews.io/api/v4/search"

    params = {
        "q": query,
        "lang": "en",
        "max": max_results,
        "apikey": api_key
    }

    try:

        response = requests.get(
            url,
            params=params,
            timeout=15
        )

        response.raise_for_status()

        data = response.json()

    except requests.RequestException as error:

        raise RuntimeError(
            "GNews request failed: " + str(error)
        )

    results = data.get("articles", [])

    articles = []

    for item in results[:max_results]:

        source_info = item.get("source", {})

        articles.append({
            "source": "GNews",
            "title": item.get("title"),
            "description": item.get("description"),
            "url": item.get("url"),
            "published_at": item.get("publishedAt"),
            "publisher": source_info.get("name")
        })

    return articles


def get_google_news_rss(query, max_results=5):

    require_text(query, "query")
    validate_max_results(max_results)

    parameters = {
        "q": query,
        "hl": "en-US",
        "gl": "US",
        "ceid": "US:en"
    }

    rss_url = (
        "https://news.google.com/rss/search?"
        + urlencode(parameters)
    )

    try:

        feed = feedparser.parse(rss_url)

    except Exception as error:

        raise RuntimeError(
            "Google News RSS request failed: "
            + str(error)
        )

    articles = []

    for item in feed.entries[:max_results]:

        articles.append({
            "source": "Google News RSS",
            "title": item.get("title"),
            "description": item.get("summary"),
            "url": item.get("link"),
            "published_at": item.get("published")
        })

    return articles